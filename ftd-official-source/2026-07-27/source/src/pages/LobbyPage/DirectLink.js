export const DirectLink = ({settings, modalFlag, setModalFlag}) => { 
    const modalRef = useRef(null)
    const [active, setActive] = useState('')

    useEffect (() => {
        modalFlag ? setActive(' active') : setActive('')
        // console.log(settings)
    }, [modalFlag])

    const onClose = () => {
        setModalFlag(false)

    }

    function copyTextToClipboard () {
        if(navigator.clipboard) { navigator.clipboard.writeText(settings.url) }
    }

    const text = `let's play Othello ${settings?.timeControl} %2b ${settings?.increment} ${settings.xot === 1 ? 'XOT' : ''}!`

    return (  
        <>
        <div className = {`modal-invite${active}`} ref = {modalRef}>
            {settings ? 
            <div className = 'card-content'>
                <div className='card-title'> 
                    <span>Share Link</span>
                    <div className = "close-icon" onClick = {onClose}>
                        <Close/>
                    </div>
                </div>
                <input className= 'modal-url' readOnly='readonly' value = {settings.url || ''}></input>
                <div className="copy-url" onClick = {copyTextToClipboard}>
                    <CopyIcon/>
                </div>

                <div className="link-control">{settings?.timeControl} min + {settings?.increment} sec {settings.xot === 1 ? ' XOT' : ''}</div>
                <div className = 'logo-container' >
                    <a className = 'share-logo' target="_blank" rel="noopener noreferrer" href={`https://api.whatsapp.com/send?text=${settings.url}`}>
                        <WhatsApp/>
                    </a>

                    <a className = 'share-logo' target="_blank" rel="noopener noreferrer" href={`https://telegram.me/share/url?url=${settings.url}&text=${text}`}>
                        <Telegram/>
                    </a>               
                </div>

            </div>
        : <></>}
        </div>
        
        </>
    )
}
