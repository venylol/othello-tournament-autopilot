export const Watch = ({setPressed, pressed, count = 0}) => {
    // const {settings, setSettings} = useContext (UserContext)     // hook???
    const [opened, setOpened] = useState(false)
    const buttonRef = useRef(null)

    const clickHandler = () => {
        setPressed('Watch')
    } 

    useEffect (() => {
        if (pressed !== 'Watch') {
            setOpened(false)
        } else {
            setOpened(true)
        }
    }, [pressed])
    
    useEffect (() => {
        if (!buttonRef.current) {return}
            buttonRef.current.style.animation = 'none' 
            buttonRef.current.style.left = '50%'
            buttonRef.current.style.top = '50%'
            requestAnimationFrame(() => {
                buttonRef.current.style.animation = 'ripples-toggle 0.3s ease-in forwards'
            })
    }, [opened])

    return (
        <>
        <div className= 'game-footer-container'> 
            <div className = {`game-footer watch ${opened? 'active' : ''}`} title = 'watch' onClick= {clickHandler}>
                <WatchSVG opened = {opened}/>
                <span className='tables-counter'>{count}</span>
                <label className = {`game-footer-label ${opened? 'active' : ''}`}>Watch</label>
            </div>
            {pressed === 'Watch' ? 
                <div className="ripple-container toggle-footer">
                    <span ref = {buttonRef} className = 'ripple'></span> 
                </div> : <></>
            }
        </div>
        </>
    )
}

